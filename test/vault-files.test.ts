import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { afterEach, describe, expect, it } from 'vitest';
import type { Project } from '../src/shared/contracts.js';
import type { VaultEntry, VaultFileBinding, VaultFileCard } from '../src/shared/vault.js';
import { VaultFiles, removeExpiredFiles, renderDotenv } from '../src/main/vault/vault-files.js';
import { git } from '../src/main/git/run-git.js';

const roots: string[] = [];
const binding: VaultFileBinding = {
  kind: 'dotenv',
  projectId: 'dashboard',
  path: '.env.local',
};

afterEach(async () => {
  await Promise.all(
    roots.splice(0).map(async (root) => rm(root, { recursive: true, force: true })),
  );
});

function project(root: string): Project {
  return {
    id: 'dashboard',
    label: 'Dashboard',
    path: root,
    actions: [],
    kind: 'watch',
    expectedPort: null,
    tags: [],
  };
}

/** A vault holding at most one file, which a test may swap out or empty between two calls. */
async function setup(
  initial: VaultEntry | undefined,
  ignored = true,
  tracked = false,
): Promise<{ root: string; files: VaultFiles; set: (next: VaultEntry | undefined) => void }> {
  const root = await mkdtemp(join(tmpdir(), 'oxum-vault-files-'));
  roots.push(root);
  let current = initial;
  return {
    root,
    files: new VaultFiles({
      vault: { entryForFile: () => current },
      projects: () => [project(root)],
      ignored: async () => ignored,
      tracked: async () => tracked,
    }),
    set: (next) => {
      current = next;
    },
  };
}

function entry(
  values: Record<string, string>,
  text = '',
  over: Partial<VaultFileCard> = {},
): VaultEntry {
  return {
    card: {
      id: 'f1',
      binding,
      createdAt: '2026-09-26T12:00:00.000Z',
      lifetimeMinutes: 30,
      generatedAt: null,
      expiresAt: null,
      secrets: Object.keys(values),
      text,
      ...over,
    },
    values,
  };
}

describe('renderDotenv', () => {
  it('writes the marker, the text as it was typed, then the secrets quoted', () => {
    const output = renderDotenv(
      entry({ API_KEY: 'a"b\\c\nnext' }, '# Account\nEMAIL=me@example.com\n\n'),
    );
    expect(output).toBe(
      '# Generated by Oxum Vault. Plaintext: readable by processes in this project. Do not edit.\n' +
        '\n' +
        '# Account\nEMAIL=me@example.com\n' +
        '\n' +
        'API_KEY="a\\"b\\\\c\\nnext"\n',
    );
  });

  it('leaves no stray blank line when there is no text', () => {
    expect(renderDotenv(entry({ API_KEY: 'v' }))).toMatch(/Do not edit\.\n\nAPI_KEY="v"\n$/);
  });
});

describe('VaultFiles', () => {
  it('generates a marked dotenv file without exposing values in the result', async () => {
    const { root, files } = await setup(entry({ API_KEY: 'secret-value' }, 'USER=me'));
    const result = await files.generate(binding);
    expect(result).toEqual({ ok: true, message: 'Generated .env.local with 1 secret.' });
    expect(result.message).not.toContain('secret-value');
    const written = await readFile(join(root, '.env.local'), 'utf8');
    expect(written).toContain('USER=me\n');
    expect(written).toContain('API_KEY="secret-value"');
  });

  it('generates a file holding text only', async () => {
    const { files } = await setup(entry({}, 'EMAIL=me@example.com'));
    expect(await files.generate(binding)).toEqual({
      ok: true,
      message: 'Generated .env.local with 0 secrets.',
    });
  });

  it('refuses a file with nothing to write', async () => {
    const { files } = await setup(entry({}, '  \n'));
    expect(await files.generate(binding)).toEqual({
      ok: false,
      message: 'This file has nothing to write.',
    });
  });

  it('refuses to generate a file Git does not ignore', async () => {
    const { root, files } = await setup(entry({ API_KEY: 'secret-value' }), false);
    expect(await files.generate(binding)).toEqual({
      ok: false,
      message: '.env.local is not ignored by Git. Add it to .gitignore first.',
    });
    await expect(readFile(join(root, '.env.local'), 'utf8')).rejects.toMatchObject({
      code: 'ENOENT',
    });
  });

  it('refuses to put secrets in a file already tracked by Git', async () => {
    const { root, files } = await setup(entry({ API_KEY: 'secret-value' }), true, true);
    expect(await files.generate(binding)).toEqual({
      ok: false,
      message: '.env.local is already tracked by Git and was not touched.',
    });
    await expect(readFile(join(root, '.env.local'), 'utf8')).rejects.toMatchObject({
      code: 'ENOENT',
    });
  });

  it('never overwrites or removes a file it does not own', async () => {
    const { root, files, set } = await setup(entry({ API_KEY: 'secret-value' }));
    await writeFile(join(root, '.env.local'), 'HAND_WRITTEN=yes\n', 'utf8');
    expect((await files.generate(binding)).ok).toBe(false);
    expect(await files.expire(binding)).toBe(true);
    // Removing the card syncs its file away, which must not touch one the vault did not write.
    set(undefined);
    await files.sync([binding]);
    expect(await readFile(join(root, '.env.local'), 'utf8')).toBe('HAND_WRITTEN=yes\n');
  });

  it('refuses a secret the text also sets', async () => {
    const { files } = await setup(entry({ API_KEY: 'first' }, 'api_key=second'));
    expect(await files.generate(binding)).toEqual({
      ok: false,
      message: 'api_key is a secret and is also set in the text.',
    });
  });

  it('rewrites a generated file after an edit, and removes it once its card is gone', async () => {
    const { root, files, set } = await setup(entry({ API_KEY: 'old' }));
    expect((await files.generate(binding)).ok).toBe(true);
    set(entry({ API_KEY: 'new' }, 'USER=me'));
    await files.sync([binding]);
    const written = await readFile(join(root, '.env.local'), 'utf8');
    expect(written).toContain('API_KEY="new"');
    expect(written).toContain('USER=me');
    set(undefined);
    await files.sync([binding]);
    await expect(readFile(join(root, '.env.local'), 'utf8')).rejects.toMatchObject({
      code: 'ENOENT',
    });
  });

  it('does not create a missing file on sync: saving never writes a secret without a click', async () => {
    const { root, files } = await setup(entry({ API_KEY: 'value' }));
    await files.sync([binding]);
    await expect(readFile(join(root, '.env.local'), 'utf8')).rejects.toMatchObject({
      code: 'ENOENT',
    });
  });

  it('uses Git itself to require an ignored, untracked target', async () => {
    const root = await mkdtemp(join(tmpdir(), 'oxum-vault-files-git-'));
    roots.push(root);
    await git(root, ['init', '--quiet']);
    await writeFile(join(root, '.gitignore'), '.env.local\n', 'utf8');
    const files = new VaultFiles({
      vault: { entryForFile: () => entry({ API_KEY: 'secret-value' }) },
      projects: () => [project(root)],
    });
    expect((await files.generate(binding)).ok).toBe(true);

    await git(root, ['add', '--force', '--', '.env.local']);
    expect(await files.generate(binding)).toEqual({
      ok: false,
      message: '.env.local is already tracked by Git and was not touched.',
    });
  });
});

describe('removeExpiredFiles', () => {
  const NOW = new Date('2026-09-26T12:00:00.000Z');

  it('deletes a file whose time is up, records it, and says something changed', async () => {
    const due = entry({ API_KEY: 'value' }, '', {
      generatedAt: '2026-09-26T11:30:00.000Z',
      expiresAt: '2026-09-26T11:59:00.000Z',
    });
    const { root, files } = await setup(due);
    expect((await files.generate(binding)).ok).toBe(true);
    const removed: string[] = [];
    const vault = {
      expired: () => [due.card],
      markRemoved: async (id: string) => {
        removed.push(id);
      },
    };
    expect(await removeExpiredFiles(vault, files, NOW)).toBe(true);
    expect(removed).toEqual(['f1']);
    await expect(readFile(join(root, '.env.local'), 'utf8')).rejects.toMatchObject({
      code: 'ENOENT',
    });
  });

  it('writes nothing on a quiet pass', async () => {
    const { files } = await setup(entry({ API_KEY: 'value' }));
    const vault = {
      expired: () => [],
      markRemoved: async () => {
        throw new Error('a quiet pass must not write');
      },
    };
    expect(await removeExpiredFiles(vault, files, NOW)).toBe(false);
  });

  it('records a file that is already gone, so it is not retried every minute', async () => {
    const due = entry({ API_KEY: 'value' }, '', {
      generatedAt: '2026-09-26T11:30:00.000Z',
      expiresAt: '2026-09-26T11:59:00.000Z',
    });
    const { files } = await setup(due);
    const removed: string[] = [];
    const vault = {
      expired: () => [due.card],
      markRemoved: async (id: string) => {
        removed.push(id);
      },
    };
    expect(await removeExpiredFiles(vault, files, NOW)).toBe(true);
    expect(removed).toEqual(['f1']);
  });
});
